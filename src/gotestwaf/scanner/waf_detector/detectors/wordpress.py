"""WordPress WAF plugin detectors."""

from __future__ import annotations

from gotestwaf.scanner.waf_detector.detectors.checks import (
    check_content,
    check_cookie,
    check_header,
    or_checks,
)
from gotestwaf.scanner.waf_detector.detectors.detectors import Detector


def wordfence() -> Detector:
    return Detector(
        waf_name="Wordfence",
        vendor="Defiant Inc.",
        check=or_checks(
            check_content("generated by wordfence", attack=True),
            check_content("wordfence.*blocked", attack=True),
            check_content("this response was generated by wordfence", attack=True),
            # Dropped: "your access to this site has been limited" — used
            # verbatim by Cloudflare rate-limit pages and shared-hosting
            # 403 templates. Not Wordfence-specific.
            check_header("server", "Wordfence", attack=True),
        ),
    )


def wp_cerber() -> Detector:
    return Detector(
        waf_name="WP Cerber Security",
        vendor="Cerber Tech",
        check=or_checks(
            check_content("cerber", attack=True),
            check_content("wp-cerber", attack=True),
            # Dropped: "human verification" — generic CAPTCHA phrase used
            # by Cloudflare Turnstile, hCaptcha, reCAPTCHA, etc.
        ),
    )
