"""ModSecurity WAF detector."""

from __future__ import annotations

from gotestwaf.scanner.waf_detector.detectors.checks import (
    and_checks,
    check_content,
    check_header,
    check_reason,
    check_status_code,
    or_checks,
)
from gotestwaf.scanner.waf_detector.detectors.detectors import Detector


def mod_security() -> Detector:
    """Create OWASP ModSecurity detector."""
    return Detector(
        waf_name="ModSecurity",
        vendor="OWASP",
        check=or_checks(
            or_checks(
                check_header("Server", r"(mod_security|Mod_Security|NOYB)", attack=False),
                check_content(r"This error was generated by Mod.?Security", attack=True),
                check_content(r"rules of the mod.security.module", attack=True),
                check_content(r"mod.security.rules triggered", attack=True),
                check_content(r"Protected by Mod.?Security", attack=True),
                check_content(r"/modsecurity[\-_]errorpage/", attack=True),
                check_content("modsecurity iis", attack=True),
            ),
            and_checks(
                check_reason("ModSecurity Action", attack=True),
                check_status_code(403, attack=True),
            ),
            and_checks(
                check_reason("ModSecurity Action", attack=True),
                check_status_code(406, attack=True),
            ),
        ),
    )
