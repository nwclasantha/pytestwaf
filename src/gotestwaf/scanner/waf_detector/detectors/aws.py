"""AWS WAF and AWS Shield detectors."""

from __future__ import annotations

from gotestwaf.scanner.waf_detector.detectors.checks import (
    check_content,
    check_header,
    or_checks,
)
from gotestwaf.scanner.waf_detector.detectors.detectors import Detector


def aws_waf() -> Detector:
    return Detector(
        waf_name="AWS WAF",
        vendor="Amazon Web Services",
        check=or_checks(
            check_header("x-amzn-waf-action", ".", attack=True),
            check_header("x-amzn-requestid", ".", attack=True),
            check_header("x-amz-apigw-id", ".", attack=True),
            check_header("x-amz-cf-id", ".", attack=False),
            check_header("x-amz-cf-pop", ".", attack=False),
            check_content("aws_waf", attack=True),
            # "request blocked" is too generic — appears in Cloudflare,
            # nginx 403, Barracuda, and many other vendor block pages.
            # Removing it prevents the detector from firing on benign
            # responses that contain the phrase, which would short-circuit
            # `_check_blocked_or_passed` via `check_block_func` and zero
            # the True-Negative score.
        ),
    )


def aws_shield() -> Detector:
    return Detector(
        waf_name="AWS Shield",
        vendor="Amazon Web Services",
        check=or_checks(
            check_header("x-amz-server-side-encryption", ".", attack=False),
            check_content("aws shield", attack=True),
        ),
    )


def aws_cloudfront() -> Detector:
    return Detector(
        waf_name="CloudFront",
        vendor="Amazon Web Services",
        check=or_checks(
            check_header("x-amz-cf-id", ".", attack=False),
            check_header("x-amz-cf-pop", ".", attack=False),
            check_header("server", "CloudFront", attack=False),
            check_header("via", "cloudfront", attack=False),
            check_content("generated by cloudfront", attack=True),
        ),
    )
