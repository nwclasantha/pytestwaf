"""Infrastructure-as-Code generator — Terraform and CloudFormation from autofix.

Generates ready-to-deploy IaC templates from the autofix JSON output.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import structlog

logger = structlog.get_logger()


def generate_iac_files(report_file: str, waf_name: str, autofix: dict[str, Any]) -> list[str]:
    """Generate Terraform / CloudFormation / Bicep / gcloud IaC from autofix.

    Always emits AWS + Azure + GCP variants (regardless of detected WAF) so
    SREs running on any cloud can pick the right deploy file. Returns the
    list of files written.
    """
    files: list[str] = []
    multi = autofix.get("multi_cloud") or {}
    aws_data = multi.get("aws") or autofix
    azure_data = multi.get("azure") or autofix
    gcp_data = multi.get("gcp") or autofix

    aws_rules = (aws_data or {}).get("aws_rules") or autofix.get("aws_rules") or []
    if aws_rules:
        tf_path = f"{report_file}_fix.tf"
        Path(tf_path).write_text(_generate_terraform_aws(aws_rules), encoding="utf-8")
        files.append(tf_path)
        cfn_path = f"{report_file}_fix_cfn.yaml"
        Path(cfn_path).write_text(_generate_cloudformation_aws(aws_rules), encoding="utf-8")
        files.append(cfn_path)

    azure_fixes = (azure_data or {}).get("fixes") or []
    if azure_fixes:
        bicep_path = f"{report_file}_fix_azure.bicep"
        Path(bicep_path).write_text(_generate_bicep_azure(azure_fixes), encoding="utf-8")
        files.append(bicep_path)
        az_cli_path = f"{report_file}_fix_azure.sh"
        Path(az_cli_path).write_text(_generate_az_cli_script(azure_fixes), encoding="utf-8")
        files.append(az_cli_path)

    gcp_fixes = (gcp_data or {}).get("fixes") or []
    if gcp_fixes:
        gcp_tf_path = f"{report_file}_fix_gcp.tf"
        Path(gcp_tf_path).write_text(_generate_terraform_gcp(gcp_fixes), encoding="utf-8")
        files.append(gcp_tf_path)
        gcp_cli_path = f"{report_file}_fix_gcp.sh"
        Path(gcp_cli_path).write_text(_generate_gcloud_script(gcp_fixes), encoding="utf-8")
        files.append(gcp_cli_path)

    return files


def _generate_terraform_aws(aws_rules: list[dict[str, Any]]) -> str:
    """Generate a deployable Terraform module that creates an AWS WAFv2 Web ACL
    with the recommended rules. AWS WAFv2 managed rule groups can only live
    inside a Web ACL resource, so we emit a complete `aws_wafv2_web_acl` —
    the user can either deploy it as-is or copy the `rule` blocks into an
    existing Web ACL.
    """
    lines = [
        '# Auto-generated by GoTestWAF - AWS WAF fix deployment',
        '# Apply: terraform init && terraform plan && terraform apply',
        '#',
        '# This creates a complete aws_wafv2_web_acl with the recommended rules.',
        '# To merge into an EXISTING Web ACL, copy the `rule { ... }` blocks below.',
        '',
        'variable "web_acl_name" {',
        '  description = "Name for the new Web ACL (or merge target)"',
        '  type        = string',
        '  default     = "gotestwaf-fix"',
        '}',
        '',
        'variable "web_acl_scope" {',
        '  description = "REGIONAL (ALB/API GW) or CLOUDFRONT"',
        '  type        = string',
        '  default     = "REGIONAL"',
        '}',
        '',
        'resource "aws_wafv2_web_acl" "gotestwaf_fix" {',
        '  name        = var.web_acl_name',
        '  description = "GoTestWAF auto-fix WebACL"',
        '  scope       = var.web_acl_scope',
        '',
        '  default_action { allow {} }',
        '',
    ]
    for i, rule in enumerate(aws_rules):
        stmt = rule.get("Statement", {})
        name = rule.get("Name", f"gotestwaf_fix_{i}")
        tf_name = name.lower().replace("-", "_").replace(" ", "_")
        priority = rule.get("Priority", 10 + i)
        if "ManagedRuleGroupStatement" in stmt:
            mrg = stmt["ManagedRuleGroupStatement"]
            vendor = mrg.get("VendorName", "AWS")
            group_name = mrg.get("Name", "")
            lines.extend([
                '  rule {',
                f'    name     = "{name}"',
                f'    priority = {priority}',
                '    override_action { none {} }',
                '    statement {',
                '      managed_rule_group_statement {',
                f'        vendor_name = "{vendor}"',
                f'        name        = "{group_name}"',
                '      }',
                '    }',
                '    visibility_config {',
                '      sampled_requests_enabled   = true',
                '      cloudwatch_metrics_enabled = true',
                f'      metric_name                = "{tf_name}"',
                '    }',
                '  }',
                '',
            ])
        else:
            # Custom rule with non-managed Statement — emit as commented JSON
            # since the full Statement schema is too rich to translate to HCL
            # generically. User can hand-translate using the JSON as reference.
            stmt_json = json.dumps(stmt, indent=2).replace("\n", "\n  # ")
            lines.extend([
                f'  # Custom rule: {name} (priority {priority}) — translate the',
                '  # following Statement JSON into an HCL `rule { statement { ... } }` block:',
                f'  # {stmt_json}',
                '',
            ])
    lines.extend([
        '  visibility_config {',
        '    sampled_requests_enabled   = true',
        '    cloudwatch_metrics_enabled = true',
        '    metric_name                = "gotestwafFixACL"',
        '  }',
        '}',
        '',
        'output "web_acl_arn" { value = aws_wafv2_web_acl.gotestwaf_fix.arn }',
    ])
    return "\n".join(lines)


def _generate_cloudformation_aws(aws_rules: list[dict[str, Any]]) -> str:
    """Generate CloudFormation YAML for AWS WAF rules."""
    lines = [
        '# Auto-generated by GoTestWAF — AWS WAF fix deployment',
        '# Deploy: aws cloudformation deploy --template-file this_file.yaml --stack-name waf-fix',
        'AWSTemplateFormatVersion: "2010-09-09"',
        'Description: WAF rules to fix bypasses found by GoTestWAF scan',
        '',
        'Parameters:',
        '  WebACLName:',
        '    Type: String',
        '    Default: gotestwaf-fix',
        '    Description: Name for the new (or merge target) Web ACL',
        '  WebACLScope:',
        '    Type: String',
        '    Default: REGIONAL',
        '    AllowedValues: [REGIONAL, CLOUDFRONT]',
        '',
        '# This template creates a complete AWS::WAFv2::WebACL with the',
        '# recommended rules. To merge into an existing Web ACL, copy the',
        '# entries under `Rules:` into your existing WebACL definition.',
        '',
        'Resources:',
        '  GoTestWAFFixACL:',
        '    Type: AWS::WAFv2::WebACL',
        '    Properties:',
        '      Name: !Ref WebACLName',
        '      Scope: !Ref WebACLScope',
        '      Description: GoTestWAF auto-fix WebACL',
        '      DefaultAction:',
        '        Allow: {}',
        '      VisibilityConfig:',
        '        SampledRequestsEnabled: true',
        '        CloudWatchMetricsEnabled: true',
        '        MetricName: GoTestWAFFixACL',
        '      Rules:',
    ]
    for i, rule in enumerate(aws_rules):
        stmt = rule.get("Statement", {})
        name = rule.get("Name", f"GoTestWAFFix{i}")
        if "ManagedRuleGroupStatement" in stmt:
            mrg = stmt["ManagedRuleGroupStatement"]
            lines.extend([
                f'        - Name: {name}',
                f'          Priority: {rule.get("Priority", 10 + i)}',
                '          Statement:',
                '            ManagedRuleGroupStatement:',
                f'              VendorName: {mrg.get("VendorName", "AWS")}',
                f'              Name: {mrg.get("Name", "")}',
                '          OverrideAction:',
                '            None: {}',
                '          VisibilityConfig:',
                '            SampledRequestsEnabled: true',
                '            CloudWatchMetricsEnabled: true',
                f'            MetricName: {name.replace("-", "").replace(" ", "").replace("_", "")}',
            ])
    lines.extend([
        '',
        'Outputs:',
        '  WebACLArn:',
        '    Description: ARN of the created Web ACL',
        '    Value: !GetAtt GoTestWAFFixACL.Arn',
    ])
    return "\n".join(lines)


# ═══════════════════════════════════════════════════════════════
#   AZURE WAF — Bicep template (Azure Front Door + WAF Policy)
# ═══════════════════════════════════════════════════════════════

def _generate_bicep_azure(fixes: list[dict[str, Any]]) -> str:
    """Generate an Azure Bicep template that creates an Azure Front Door
    WAF Policy with the recommended managed rule sets, custom rules and
    Prevention mode. Apply with `az deployment group create -f this.bicep`.
    """
    lines = [
        "// Auto-generated by GoTestWAF - Azure Front Door WAF fix deployment",
        "// Apply: az deployment group create -g <RG> -f waf-fix.bicep",
        "//",
        "// This template configures an Azure Front Door WAF Policy with the",
        "// managed rule sets and custom rules recommended by the scan.",
        "",
        "@description('Name of the WAF policy.')",
        "param wafPolicyName string = 'gotestwafFix'",
        "",
        "@description('Resource group location.')",
        "param location string = resourceGroup().location",
        "",
        "resource wafPolicy 'Microsoft.Network/FrontDoorWebApplicationFirewallPolicies@2024-02-01' = {",
        "  name: wafPolicyName",
        "  location: 'global'",
        "  sku: { name: 'Premium_AzureFrontDoor' }",
        "  properties: {",
        "    policySettings: {",
        "      enabledState: 'Enabled'",
        "      // Prevention (not Detection) - Detection only logs.",
        "      mode: 'Prevention'",
        "      requestBodyCheck: 'Enabled'",
        "    }",
        "    managedRules: {",
        "      managedRuleSets: [",
        "        {",
        "          ruleSetType: 'Microsoft_DefaultRuleSet'",
        "          ruleSetVersion: '2.1'",
        "          ruleSetAction: 'Block'",
        "        }",
        "        {",
        "          ruleSetType: 'Microsoft_BotManagerRuleSet'",
        "          ruleSetVersion: '1.0'",
        "          ruleSetAction: 'Block'",
        "        }",
        "      ]",
        "    }",
        "    customRules: {",
        "      rules: [",
    ]
    rule_priority = 100
    for f in fixes[:10]:
        if (f.get("type") or "") in ("custom_rule", "add_custom_rule"):
            name = "".join(c for c in (f.get("name") or "Rule") if c.isalnum())[:64] or f"Rule{rule_priority}"
            lines.extend([
                "        {",
                f"          name: '{name}'",
                f"          priority: {rule_priority}",
                "          ruleType: 'MatchRule'",
                "          action: 'Block'",
                "          matchConditions: [",
                "            {",
                "              matchVariable: 'RequestBody'",
                "              operator: 'Contains'",
                "              negateCondition: false",
                "              transforms: [ 'Lowercase', 'UrlDecode' ]",
                "              matchValue: [ '<script', 'union select', '/etc/passwd' ]",
                "            }",
                "          ]",
                "        }",
            ])
            rule_priority += 10
    lines.extend([
        "      ]",
        "    }",
        "  }",
        "}",
        "",
        "output wafPolicyId string = wafPolicy.id",
        "// --- end ---",
    ])
    return "\n".join(lines)


def _generate_az_cli_script(fixes: list[dict[str, Any]]) -> str:
    """Generate a runnable bash script of az CLI commands."""
    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by GoTestWAF - Azure Front Door WAF fix (az CLI)",
        "# Set these before running:",
        'RG="${RG:-my-rg}"',
        'POLICY="${POLICY:-gotestwaf-policy}"',
        "set -e",
        "",
        "# 1. Create / update WAF policy in Prevention mode",
        'az network front-door waf-policy update --resource-group "$RG" --name "$POLICY" --mode Prevention',
        "",
        "# 2. Attach Microsoft DRS 2.1 + Bot Manager managed rule sets",
        'az network front-door waf-policy managed-rules add --resource-group "$RG" --policy-name "$POLICY" \\',
        "    --type Microsoft_DefaultRuleSet --version 2.1 --action Block",
        'az network front-door waf-policy managed-rules add --resource-group "$RG" --policy-name "$POLICY" \\',
        "    --type Microsoft_BotManagerRuleSet --version 1.0 --action Block",
        "",
    ]
    pri = 100
    for f in fixes[:10]:
        if (f.get("type") or "") in ("custom_rule", "add_custom_rule"):
            name = "".join(c for c in (f.get("name") or "Rule") if c.isalnum())[:64] or f"Rule{pri}"
            lines.extend([
                f"# Custom rule: {f.get('name','rule')}",
                'az network front-door waf-policy rule create --resource-group "$RG" --policy-name "$POLICY" \\',
                f"    --name {name} --priority {pri} --rule-type MatchRule --action Block",
                'az network front-door waf-policy rule match-condition add --resource-group "$RG" --policy-name "$POLICY" \\',
                f"    --name {name} --match-variable RequestBody --operator Contains \\",
                "    --values '<script' 'union select' '/etc/passwd' \\",
                "    --transforms Lowercase UrlDecode",
                "",
            ])
            pri += 10
    lines.append("echo 'Azure WAF policy updated. Verify in: Azure Portal > Front Door > WAF Policies'")
    return "\n".join(lines)


